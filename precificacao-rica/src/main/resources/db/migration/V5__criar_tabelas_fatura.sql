CREATE TABLE fatura (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_criacao TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
  tipo_desconto VARCHAR(12),
  valor_desconto NUMERIC,
  CONSTRAINT ck_fatura_desconto CHECK (
    (tipo_desconto IS NULL AND valor_desconto IS NULL)
    OR (
      tipo_desconto IS NOT NULL
      AND valor_desconto IS NOT NULL
      AND valor_desconto >= 0
      AND valor_desconto NOT IN ('NaN'::numeric, 'Infinity'::numeric)
      AND (
        (tipo_desconto = 'PERCENTUAL' AND valor_desconto <= 100
          AND valor_desconto = TRUNC(valor_desconto, 4))
        OR (tipo_desconto = 'VALOR_FIXO' AND valor_desconto = TRUNC(valor_desconto, 2))
      )
    )
  )
);

CREATE TABLE item_fatura (
  fatura_id BIGINT NOT NULL REFERENCES fatura (id),
  produto_codigo BIGINT NOT NULL REFERENCES produto (codigo),
  quantidade NUMERIC(19, 4) NOT NULL,
  posicao INTEGER NOT NULL,
  PRIMARY KEY (fatura_id, produto_codigo),
  UNIQUE (fatura_id, posicao),
  CONSTRAINT ck_item_fatura_quantidade CHECK (quantidade > 0 AND quantidade <> 'NaN'::numeric),
  CONSTRAINT ck_item_fatura_posicao CHECK (posicao >= 0)
);
