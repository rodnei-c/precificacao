CREATE TABLE cidade (
  codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(200) NOT NULL,
  uf VARCHAR(2) NOT NULL,
  CONSTRAINT ck_cidade_nome CHECK (LENGTH(TRIM(nome)) > 0),
  CONSTRAINT ck_cidade_uf CHECK (uf IN (
    'AC', 'AL', 'AM', 'AP', 'BA', 'CE', 'DF', 'ES', 'GO', 'MA', 'MG', 'MS', 'MT', 'PA',
    'PB', 'PE', 'PI', 'PR', 'RJ', 'RN', 'RO', 'RR', 'RS', 'SC', 'SE', 'SP', 'TO'
  ))
);

CREATE UNIQUE INDEX ux_cidade_nome_uf ON cidade (LOWER(nome), uf);
