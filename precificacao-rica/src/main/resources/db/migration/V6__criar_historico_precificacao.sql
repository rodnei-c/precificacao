CREATE TABLE historico_precificacao (
  codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produto_codigo BIGINT NOT NULL REFERENCES produto (codigo),
  data_alteracao TIMESTAMP NOT NULL DEFAULT (statement_timestamp()::timestamp),
  custo_anterior NUMERIC(19, 2) NOT NULL,
  preco_venda_anterior NUMERIC(19, 2) NOT NULL,
  percentual_anterior NUMERIC(19, 4) NOT NULL,
  custo_novo NUMERIC(19, 2) NOT NULL,
  preco_venda_novo NUMERIC(19, 2) NOT NULL,
  percentual_novo NUMERIC(19, 4) NOT NULL
);

CREATE INDEX ix_historico_precificacao_produto_codigo
  ON historico_precificacao (produto_codigo, codigo DESC);
