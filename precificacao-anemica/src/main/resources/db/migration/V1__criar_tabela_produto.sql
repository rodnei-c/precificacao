CREATE TABLE produto (
  codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(200) NOT NULL,
  custo NUMERIC(19, 2) NOT NULL,
  preco_venda NUMERIC(19, 2) NOT NULL,
  percentual NUMERIC(19, 4) NOT NULL,
  modalidade_precificacao VARCHAR(30) NOT NULL,
  CONSTRAINT ck_produto_nome CHECK (LENGTH(TRIM(nome)) > 0),
  CONSTRAINT ck_produto_custo CHECK (custo > 0),
  CONSTRAINT ck_produto_venda CHECK (preco_venda >= custo),
  CONSTRAINT ck_produto_percentual CHECK (percentual >= 0),
  CONSTRAINT ck_produto_modalidade CHECK (
    modalidade_precificacao IN ('ACRESCIMO_SOBRE_CUSTO', 'MARGEM_SOBRE_VENDA')
  ),
  CONSTRAINT ck_produto_margem CHECK (
    modalidade_precificacao <> 'MARGEM_SOBRE_VENDA' OR percentual < 100
  ),
  CONSTRAINT ck_produto_percentual_positivo CHECK (percentual = 0 OR preco_venda > custo)
);
