CREATE TABLE cliente (
  codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(200) NOT NULL,
  cpf VARCHAR(11) NOT NULL UNIQUE,
  email VARCHAR(254) NOT NULL,
  telefone VARCHAR(30),
  cep VARCHAR(8),
  logradouro VARCHAR(200),
  numero VARCHAR(20),
  bairro VARCHAR(100),
  complemento VARCHAR(100),
  cidade_codigo BIGINT REFERENCES cidade (codigo),
  CONSTRAINT ck_cliente_nome CHECK (LENGTH(TRIM(nome)) > 0),
  CONSTRAINT ck_cliente_cpf CHECK (cpf ~ '^[0-9]{11}$'),
  CONSTRAINT ck_cliente_email CHECK (LENGTH(TRIM(email)) > 0),
  CONSTRAINT ck_cliente_cep CHECK (cep ~ '^[0-9]{8}$'),
  CONSTRAINT ck_cliente_endereco CHECK (
    num_nonnulls(cep, logradouro, numero, bairro, cidade_codigo) IN (0, 5)
    AND (cep IS NOT NULL OR complemento IS NULL)
  )
);

CREATE UNIQUE INDEX ux_cliente_email ON cliente (LOWER(email));
CREATE INDEX ix_cliente_cidade ON cliente (cidade_codigo);
